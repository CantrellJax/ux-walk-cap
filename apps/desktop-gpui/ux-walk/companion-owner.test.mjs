import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import { NativeBrowserEvidence } from "./native-browser.mjs";
import { projectBrowserEvidence } from "./browser-evidence.mjs";

test("external evidence owner durably accepts bound Meet captions, projects pause clock, and preserves source evidence without video", async (t) => {
	const root = fs.mkdtempSync("/tmp/cap-companion-owner-");
	t.after(() => fs.rmSync(root, { recursive: true, force: true }));
	const work = path.join(root, "work"), directory = path.join(root, "walk");
	fs.mkdirSync(directory);
	const file = path.join(directory, "native-walk.json"), project = path.join(root, "source.cap");
	fs.mkdirSync(project);
	const journal = { schemaVersion: 1, state: "recording", startedAtMs: 1000, request: { directory, topic: "Synthetic", speakers: [] }, sourceProject: project, events: [], durationMs: null };
	fs.writeFileSync(file, JSON.stringify(journal));
	let now = 1000;
	const evidence = new NativeBrowserEvidence("11111111-1111-4111-8111-111111111111", work, () => now);
	evidence.windowId = "55";
	evidence.start(file, "55", { mode: "external" });
	t.after(() => { if (evidence.active) evidence.finish(file, "failed"); });
	const session = evidence.companion();
	const hello = await session.handle({ type: "companion-hello", clientId: "profile-client-123456" });
	const b = await session.handle({ type: "companion-attach", recordingId: hello.recordingId, generation: hello.generation, clientId: "profile-client-123456", role: "meet", tabId: 9, windowId: 3, documentId: "meet-doc", url: "https://meet.google.com/abc-defg-hij" });
	now = 2000;
	await session.handle({ type: "companion-events", ...b, events: [{ eventId: "caption-1", observedAt: 2000, kind: "caption", name: "Clay", text: "Before pause", captionId: "turn-1", revision: 1 }] });
	evidence.anchor(file, 2000, 1000, true);
	now = 7000;
	await assert.rejects(session.handle({ type: "companion-events", ...b, events: [{ eventId: "paused", observedAt: 7000, kind: "caption", name: "Wrong", text: "Excluded", captionId: "turn-x", revision: 1 }] }));
	evidence.anchor(file, 7000, 1000, false);
	now = 8000;
	await session.handle({ type: "companion-events", ...b, events: [{ eventId: "caption-2", observedAt: 8000, kind: "caption", name: "Jackson", text: "After pause", captionId: "turn-2", revision: 1 }] });
	evidence.finish(file);
	const projected = projectBrowserEvidence(file, { ...journal, durationMs: 3000 });
	const captions = projected.events.filter((event) => event.ev === "meet-caption");
	assert.deepEqual(captions.map((event) => [event.name, event.t]), [["Clay", 2000], ["Jackson", 3000]]);
	assert.equal(captions[1].observedAt, 8000);
	assert.match(projected.coverage.console, /not captured/i);
	assert.equal(fs.existsSync(path.join(directory, "browser-evidence.jsonl")), true);
	assert.equal(fs.existsSync(path.join(directory, "video.mp4")), false);
});
